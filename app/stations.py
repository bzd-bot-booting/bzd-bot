CITIES = ["Брест", "Витебск", "Гомель", "Гродно", "Минск", "Могилев"]

SMART_STATIONS = {
    "минск": "Минск-Пассажирский",
    "минск-пассажирский": "Минск-Пассажирский",
    "брест": "Брест-Центральный",
    "брест-центральный": "Брест-Центральный",
    "гомель": "Гомель",
    "витебск": "Витебск",
    "могилев": "Могилев",
    "могилёв": "Могилев",
    "гродно": "Гродно",
}


def normalize_station(value: str) -> str:
    value = " ".join((value or "").strip().split())
    if not value:
        raise ValueError("Название станции не может быть пустым")
    return SMART_STATIONS.get(value.casefold(), value)
